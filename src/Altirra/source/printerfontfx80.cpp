consteval void ATPrinterFontFX80::Write(
	int offset,
	const char *src0,
	const char *src1,
	const char *src2,
	const char *src3,
	const char *src4,
	const char *src5,
	const char *src6,
	const char *src7,
	const char *src8)
{
	const char *srcs[9] = {
		src0,
		src1,
		src2,
		src3,
		src4,
		src5,
		src6,
		src7,
		src8,
	};

	for(int i = 0; i < 8; ++i) {
		uint8 start = 12;
		uint8 end = 0;

		for(int j = 0; j < 12; ++j) {
			uint16 v = 0;

			for(int k = 0; k < 9; ++k) {
				const char c = *srcs[k]++;

				if (c == '/') {
					// nothing
				} else {
					if (k == 0) {
						if (start > j)
							start = j;

						if (end < j)
							end = j;
					}

					if (c == '#')
						v |= 0x100 >> k;
					else if (c != '.')
						throw;
				}
			}

			mFont[offset][j] = v;
		}

		if (start > end)
			throw;

		mPropStartStop[offset][0] = start;
		mPropStartStop[offset][1] = end;

		++offset;

		const char endChar = (i == 7) ? 0 : '|';

		for(int j = 0; j < 9; ++j) {
			if (*srcs[j]++ != endChar)
				throw;
		}
	}
}


